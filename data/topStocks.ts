export function searchTopStocks(query: string, limit = 8): TopStock[] {
  const q = query.trim().toUpperCase();
  if (!q) return [];

  // Deduplicate by ticker
  const seen = new Set<string>();
  const results: TopStock[] = [];

  for (const stock of TOP_STOCKS) {
    if (seen.has(stock.ticker)) continue;
    seen.add(stock.ticker);
    // Prefix match on ticker, or word-start match on name
    const tickerMatch = stock.ticker.startsWith(q);
    const nameMatch = stock.name.toUpperCase().split(/\s+/).some((w) => w.startsWith(q));
    if (tickerMatch || nameMatch) {
      results.push(stock);
      if (results.length >= limit) break;
    }
  }

  return results;
}
